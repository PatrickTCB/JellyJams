import Foundation
import JellyfinAPI
import OSLog
import SwiftUI

private let sessionLogger = Logger(
    subsystem: Bundle.main.bundleIdentifier ?? "net.aseriesoftubes.JellyJams",
    category: "Session"
)

/// Owns the signed-in state: the SDK-backed ``JellyfinService``, the current
/// user, and persistence of both. This is the single source of truth other
/// services and views read the client from.
@MainActor
@Observable
final class SessionStore {

    struct StoredUser: Codable, Sendable, Equatable {
        var id: String
        var name: String
        var serverURL: URL
        var serverName: String?
    }

    private(set) var client: JellyfinService?
    private(set) var currentUser: StoredUser?
    private(set) var isRestoring = true
    private(set) var errorMessage: String?
    private(set) var serverReachable: Bool = true

    /// Identifies this device to the server. Generated once at launch —
    /// and regenerated by ``regenerateDeviceIdentity()`` when a sign-out
    /// resets the app to its fresh-install state.
    private(set) var deviceInfo = DeviceInfo.current()

    /// The URLSession configuration sign-in probes are built with — nil
    /// uses the app's default setup; tests inject a stubbed one so a whole
    /// sign-in flow runs against canned answers.
    private let sessionConfiguration: URLSessionConfiguration?
    /// The wait between Quick Connect approval polls. Five seconds is the
    /// cadence Jellyfin clients poll at; tests shrink it so a flow runs at
    /// full speed.
    private let quickConnectPollInterval: Duration

    init(
        sessionConfiguration: URLSessionConfiguration? = nil,
        quickConnectPollInterval: Duration = .seconds(5)
    ) {
        self.sessionConfiguration = sessionConfiguration
        self.quickConnectPollInterval = quickConnectPollInterval
    }

    /// Takes a freshly generated device identity, as a fresh install would
    /// present on first launch: the persisted id is dropped and a new one
    /// generated in its place, so the next sign-in appears on the server as
    /// a brand-new device. Part of the reset a server sign-out performs.
    func regenerateDeviceIdentity() {
        UserDefaults.standard.removeObject(forKey: DeviceInfo.deviceIdDefaultsKey)
        deviceInfo = DeviceInfo.current()
    }

    private let userDefaultsKey = "jellyjams.currentUser"

    var isSignedIn: Bool { client != nil && currentUser != nil }

    /// The gateway the UI's library reads go through. It exists whether
    /// or not a user is signed in — reads made while signed out throw
    /// ``JellyfinError/notAuthenticated`` instead of silently doing nothing.
    var library: LibraryRepository { LibraryRepository(client: client) }

    // MARK: - Online status

    /// Identifies the newest reachability check. Checks overlap whenever the
    /// network changes mid-ping, and a ping sent on the network the device
    /// just left can time out *after* the new network's ping succeeded.
    @ObservationIgnored private var latestReachabilityCheck = UUID()

    /// Pings the signed-in server. Many servers are only reachable on the
    /// home network, so this answers "online" for the server, not the device.
    /// Only the newest check's answer is kept.
    func checkServerReachability() async {
        let check = UUID()
        latestReachabilityCheck = check
        let reachable = await client?.ping() ?? false
        guard check == latestReachabilityCheck else { return }
        serverReachable = reachable
    }
    
    // MARK: - Restore

    func restore() {
        isRestoring = true
        defer { isRestoring = false }
        errorMessage = nil

        guard let data = UserDefaults.standard.data(forKey: userDefaultsKey) else { return }

        let user: StoredUser
        do {
            user = try JSONDecoder().decode(StoredUser.self, from: data)
        } catch {
            UserDefaults.standard.removeObject(forKey: userDefaultsKey)
            errorMessage = "The saved account information was damaged and has been cleared."
            return
        }

        do {
            guard let token = try Keychain.get(account: user.id) else {
                UserDefaults.standard.removeObject(forKey: userDefaultsKey)
                return
            }
            let credentials = ServerCredentials(userId: user.id, token: token)
            client = JellyfinService(baseURL: user.serverURL, deviceInfo: deviceInfo, credentials: credentials)
            currentUser = user
        } catch {
            errorMessage = error.userFacingMessage
        }
    }

    // MARK: - Sign in / out

    func signIn(serverURLString: String, username: String, password: String) async throws {
        let baseURL = try Self.normalizeServerURL(serverURLString)
        let probe = JellyfinService(baseURL: baseURL, deviceInfo: deviceInfo, sessionConfiguration: sessionConfiguration)
        let info = try await probe.publicSystemInfo()
        let auth = try await probe.authenticateByName(username: username, password: password)
        try await completeSignIn(
            probe: probe,
            auth: auth,
            baseURL: baseURL,
            serverName: info.serverName,
            fallbackName: username
        )
    }

    /// Sign in with Quick Connect: the server hands out a short code, the
    /// user approves it on a device already signed in to that server, and
    /// this device polls until the approval lands, then completes the
    /// sign-in exactly like a password one. No username or password is
    /// typed here, which is what makes it the natural flow on tvOS.
    ///
    /// The returned stream yields the code once, for the UI to show, and
    /// stays open while it polls. It finishes when the sign-in has landed —
    /// the session is signed in by then — and throws if the flow fails.
    /// Cancelling the consuming task stops the polling and leaves the
    /// session signed out.
    func quickConnectSignIn(serverURLString: String) -> AsyncThrowingStream<String, Error> {
        AsyncThrowingStream { continuation in
            let task = Task { @MainActor in
                do {
                    let baseURL = try Self.normalizeServerURL(serverURLString)
                    let probe = JellyfinService(baseURL: baseURL, deviceInfo: deviceInfo, sessionConfiguration: sessionConfiguration)
                    let info = try await probe.publicSystemInfo()
                    guard await probe.isQuickConnectEnabled() else {
                        throw JellyfinError.quickConnectNotEnabled
                    }
                    let (secret, code) = try await probe.initiateQuickConnect()
                    continuation.yield(code)

                    try await pollForQuickConnectApproval(probe: probe, secret: secret)

                    let auth = try await probe.authenticateWithQuickConnect(secret: secret)
                    try await completeSignIn(
                        probe: probe,
                        auth: auth,
                        baseURL: baseURL,
                        serverName: info.serverName,
                        fallbackName: ""
                    )
                    continuation.finish()
                } catch {
                    continuation.finish(throwing: error)
                }
            }
            continuation.onTermination = { _ in
                task.cancel()
            }
        }
    }

    /// Polls the server until the user approves the Quick Connect code.
    /// Approval is the `Authenticated` flag on the connect endpoint; a
    /// secret the server has expired answers 404, which surfaces as
    /// ``JellyfinError/quickConnectExpired`` and ends the wait. Transient
    /// network failures are tolerated for a few consecutive polls so a
    /// momentary blip doesn't abandon a code the user is mid-way through
    /// typing; a cancelled task stops at once.
    private func pollForQuickConnectApproval(probe: JellyfinService, secret: String) async throws {
        let maxPolls = 200
        let failureTolerance = 5
        var consecutiveFailures = 0

        for _ in 0 ..< maxPolls {
            try Task.checkCancellation()
            do {
                if try await probe.isQuickConnectAuthenticated(secret: secret) {
                    return
                }
                consecutiveFailures = 0
            } catch JellyfinError.quickConnectExpired {
                throw JellyfinError.quickConnectExpired
            } catch {
                if error.isCancellation { throw error }
                consecutiveFailures += 1
                guard consecutiveFailures <= failureTolerance else { throw error }
            }
            try await Task.sleep(for: quickConnectPollInterval)
        }
        throw JellyfinError.quickConnectExpired
    }

    /// The shared tail of every sign-in: validate the authentication
    /// answer, persist the token and user, and adopt the authenticated
    /// client. A failed persistence rolls the token back and invalidates
    /// the session so a half-saved sign-in never leaves a live token behind.
    /// `fallbackName` names the user when the server's answer omits a name —
    /// the typed username for a password sign-in; Quick Connect has none, so
    /// a nameless answer there is treated as incomplete.
    private func completeSignIn(
        probe: JellyfinService,
        auth: JellyfinAPI.AuthenticationResult,
        baseURL: URL,
        serverName: String?,
        fallbackName: String
    ) async throws {
        guard let authenticatedUser = auth.user,
              let userId = authenticatedUser.id,
              let accessToken = auth.accessToken
        else {
            throw JellyfinError.incompleteAuthenticationResponse
        }
        let name = authenticatedUser.name ?? fallbackName
        guard !name.isEmpty else { throw JellyfinError.incompleteAuthenticationResponse }

        let credentials = ServerCredentials(userId: userId, token: accessToken)
        let authenticatedClient = probe.authenticated(with: credentials)
        let user = StoredUser(
            id: userId,
            name: name,
            serverURL: baseURL,
            serverName: serverName
        )

        do {
            try Keychain.set(accessToken, account: user.id)
            let encoded = try JSONEncoder().encode(user)
            UserDefaults.standard.set(encoded, forKey: userDefaultsKey)
        } catch {
            do {
                try Keychain.delete(account: user.id)
            } catch {
                sessionLogger.error("Could not roll back Keychain token: \(error.localizedDescription, privacy: .public)")
            }
            do {
                try await authenticatedClient.logout()
            } catch {
                sessionLogger.error("Could not invalidate failed sign-in session: \(error.localizedDescription, privacy: .public)")
            }
            throw error
        }

        errorMessage = nil
        client = authenticatedClient
        currentUser = user
    }

    func signOut() {
        var keychainError: String?
        do {
            if let userId = currentUser?.id {
                try Keychain.delete(account: userId)
            }
        } catch {
            keychainError = "You were signed out locally, but the saved token could not be removed. \(error.userFacingMessage)"
        }

        let clientToLogout = client
        UserDefaults.standard.removeObject(forKey: userDefaultsKey)
        client = nil
        currentUser = nil
        errorMessage = keychainError
        Task {
            do {
                try await clientToLogout?.logout()
            } catch {
                sessionLogger.error("Could not invalidate signed-out session: \(error.localizedDescription, privacy: .public)")
            }
        }
    }

    func dismissError() {
        errorMessage = nil
    }

    // MARK: - Helpers

    /// Normalises user-entered server addresses: trims whitespace, adds a
    /// scheme if missing (defaults to `http` for LAN servers), and removes a
    /// trailing slash or `/web` suffix.
    static func normalizeServerURL(_ raw: String) throws -> URL {
        var text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty else { throw JellyfinError.invalidServerURL }
        if !text.contains("://") { text = "http://" + text }

        guard var components = URLComponents(string: text),
              let scheme = components.scheme?.lowercased(),
              scheme == "http" || scheme == "https",
              components.host?.isEmpty == false,
              components.user == nil,
              components.password == nil,
              components.query == nil,
              components.fragment == nil
        else {
            throw JellyfinError.invalidServerURL
        }

        components.scheme = scheme
        while components.path.hasSuffix("/") { components.path.removeLast() }
        if components.path.lowercased().hasSuffix("/web") {
            components.path.removeLast(4)
        }
        while components.path.hasSuffix("/") { components.path.removeLast() }

        guard let url = components.url else { throw JellyfinError.invalidServerURL }
        return url
    }
}
